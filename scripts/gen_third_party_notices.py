#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md: the licence texts of everything compiled into the binaries.

    python3 scripts/gen_third_party_notices.py LLAMA_CPP_DIR > THIRD_PARTY_NOTICES.md

Rust crates come from `cargo metadata` and their own LICENSE/COPYING/NOTICE files in the cargo
registry cache (run `cargo fetch` first); llama.cpp, ggml and the vendored nlohmann/json come
from the llama.cpp checkout the engine is built against. Identical texts are printed once.
"""
import glob
import hashlib
import unicodedata
import json
import os
import subprocess
import sys

llama = sys.argv[1]
meta = json.loads(subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked"],
                                 capture_output=True, text=True, check=True).stdout)
groups = {}  # sha256 -> (text, [labels])


def ascii_only(text):
    """Keep the file plain ASCII: (c) for the copyright sign, accents dropped, other symbols to ?."""
    text = text.replace("\u00a9", "(c)")
    text = unicodedata.normalize("NFKD", text)
    return "".join(c if ord(c) < 128 else ("" if unicodedata.combining(c) else "?") for c in text)


def add(label, text):
    text = ascii_only(text).strip("\n") + "\n"
    h = hashlib.sha256(" ".join(text.split()).encode()).hexdigest()
    groups.setdefault(h, (text, []))[1].append(label)


for p in sorted(meta["packages"], key=lambda p: (p["name"], p["version"])):
    if p["name"] == "banach":
        continue
    d = os.path.dirname(p["manifest_path"])
    files = sorted(f for pat in ("LICENSE*", "LICENCE*", "COPYING*", "NOTICE*", "UNLICENSE*")
                   for f in glob.glob(os.path.join(d, pat)) if os.path.isfile(f))
    label = f"{p['name']} {p['version']} ({p['license'] or 'see its repository'})"
    if not files:
        add(label, f"No licence file shipped in the crate; declared licence: {p['license']}. See {p['repository'] or 'crates.io'}.")
    for f in files:
        add(label, open(f, encoding="utf-8", errors="replace").read())

for label, rel in [("llama.cpp and ggml (MIT)", "LICENSE"), ("nlohmann/json, vendored in llama.cpp (MIT)", "licenses/LICENSE-jsonhpp")]:
    add(label, open(os.path.join(llama, rel), encoding="utf-8", errors="replace").read())
add("libstdc++ and libgcc, linked statically on Linux (GPL-3.0 with the GCC Runtime Library Exception)",
    "The GNU C++ runtime is linked into banach-engine under the GCC Runtime Library Exception, version 3.1:\n"
    "https://www.gnu.org/licenses/gcc-exception-3.1.html. Its source is available from https://gcc.gnu.org/.")

out = ["# Third-party notices\n",
       "Banach is Apache-2.0 (see LICENSE). The binaries in the Python wheels and release archives include\n"
       "the software below. This file is generated by scripts/gen_third_party_notices.py from the licence\n"
       "files shipped with each component; identical texts are listed once with every component they cover.\n"
       "Non-ASCII characters (the copyright sign, accents) are transliterated to keep the file plain ASCII.\n"]
for _, (text, labels) in sorted(groups.items(), key=lambda kv: kv[1][1][0].lower()):
    out.append("\n---\n\n" + "\n".join(f"- {l}" for l in labels) + "\n\n```text\n" + text.replace("```", "'''") + "```\n")
sys.stdout.write("".join(out))
